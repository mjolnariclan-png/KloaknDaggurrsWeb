create or replace view public.public_factions
with (security_invoker = false)
as
select
  id,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then slug else format('classified-faction-%s',lpad((sort_order/10)::text,2,'0')) end as slug,
  rune, accent, sort_order, reveal_at,
  (revealed or (reveal_at is not null and reveal_at <= now())) as is_live,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then name else 'CLASSIFIED' end as name,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then tagline else 'The Veil has not lifted.' end as tagline,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then lore else null end as lore,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then doctrine else null end as doctrine,
  case when revealed or (reveal_at is not null and reveal_at <= now()) then image_url else null end as image_url
from public.factions;

create or replace view public.public_cards
with (security_invoker = false)
as
select
  c.id,
  case when c.revealed or (c.reveal_at is not null and c.reveal_at <= now()) then c.slug else format('classified-card-%s',lpad(c.card_number::text,3,'0')) end as slug,
  c.card_number, c.rarity, c.card_type, c.sort_order, c.reveal_at, c.faction_id,
  case when f.revealed or (f.reveal_at is not null and f.reveal_at <= now()) then f.slug else null end as faction_slug,
  case when f.revealed or (f.reveal_at is not null and f.reveal_at <= now()) then f.name else 'UNKNOWN' end as faction_name,
  (c.revealed or (c.reveal_at is not null and c.reveal_at <= now())) as is_live,
  case when c.revealed or (c.reveal_at is not null and c.reveal_at <= now()) then c.name else 'CLASSIFIED' end as name,
  case when c.revealed or (c.reveal_at is not null and c.reveal_at <= now()) then c.ability else null end as ability,
  case when c.revealed or (c.reveal_at is not null and c.reveal_at <= now()) then c.lore else null end as lore,
  case when c.revealed or (c.reveal_at is not null and c.reveal_at <= now()) then c.image_url else null end as image_url
from public.cards c
left join public.factions f on f.id = c.faction_id;

