-- ---------- Accounts / existing-project compatibility ----------
-- If public.profiles already exists from an older Supabase starter,
-- CREATE TABLE IF NOT EXISTS will not add new V5 columns. Create the
-- minimal table if necessary, then migrate the existing one in place.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade
);

alter table public.profiles
  add column if not exists created_at timestamptz default now(),
  add column if not exists email text,
  add column if not exists display_name text default '',
  add column if not exists role text default 'player',
  add column if not exists active boolean default true;

-- Normalize any null/blank legacy values before adding constraints.
update public.profiles
set
  created_at = coalesce(created_at, now()),
  display_name = coalesce(display_name, ''),
  role = coalesce(nullif(role,''), 'player'),
  active = coalesce(active, true);

-- Backfill email and display name from Supabase Auth for existing accounts.
update public.profiles p
set
  email = coalesce(nullif(p.email,''), u.email),
  display_name = case
    when coalesce(p.display_name,'') = '' then
      coalesce(
        nullif(u.raw_user_meta_data->>'display_name',''),
        nullif(u.raw_user_meta_data->>'full_name',''),
        split_part(coalesce(u.email,''),'@',1)
      )
    else p.display_name
  end,
  created_at = coalesce(p.created_at, u.created_at, now())
from auth.users u
where p.id = u.id;

-- Add the V5 role check safely on an existing table.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.profiles'::regclass
      and conname = 'profiles_role_check'
  ) then
    alter table public.profiles
      add constraint profiles_role_check
      check (role in ('player','admin','owner'));
  end if;
end $$;

alter table public.profiles
  alter column created_at set default now(),
  alter column display_name set default '',
  alter column role set default 'player',
  alter column active set default true;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id,email,display_name,created_at,role,active)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(new.raw_user_meta_data->>'display_name',''),
      nullif(new.raw_user_meta_data->>'full_name',''),
      split_part(coalesce(new.email,''),'@',1)
    ),
    coalesce(new.created_at, now()),
    'player',
    true
  )
  on conflict (id) do update
  set
    email = coalesce(excluded.email, public.profiles.email),
    display_name = case
      when coalesce(public.profiles.display_name,'') = ''
        then excluded.display_name
      else public.profiles.display_name
    end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Backfill profiles for Auth users that do not yet have a public profile.
insert into public.profiles(id,email,display_name,created_at,role,active)
select
  id,
  email,
  coalesce(
    nullif(raw_user_meta_data->>'display_name',''),
    nullif(raw_user_meta_data->>'full_name',''),
    split_part(coalesce(email,''),'@',1)
  ),
  coalesce(created_at,now()),
  'player',
  true
from auth.users
on conflict(id) do nothing;

